#ifndef __KEYPAD_H
#define __KEYPAD_H

#include "ti_msp_dl_config.h"
#include <stdint.h>

/**********************************************************
 *** 4x4 矩阵键盘扫描模块 (天猛星 MSPM0G3507)
 ***
 *** 硬件接线:
 ***   行 R1-R4 (扫描输出, 逐行拉低): R1=PA28, R2=PA31, R3=PB4, R4=PB5
 ***   列 C1-C4 (输入上拉, 按下读0):   C1=PA9,  C2=PA8,  C3=PA1, C4=PA0
 ***
 *** 扫描方式: 行出列入
 ***   1. 全部行拉高(不选中)
 ***   2. 逐行拉低(选中该行), 读 C1-C4
 ***   3. 哪列读到低 = 该行×该列交叉键按下
 ***
 *** 键号布局 (只用 S1-S8, R3/R4 行预留):
 ***         C1(PA9)  C2(PA8)  C3(PA1)  C4(PA0)
 ***   R1(PA28): S1       S2       S3       S4
 ***   R2(PA31): S5       S6       S7       S8
 ***   R3(PB4):   -        -        -        -
 ***   R4(PB5):   -        -        -        -
 ***
 *** 返回值: 1-8 表示当前按住的键 S1-S8, 0=无键按下
 *** 语义: 速度模式 -- 按住期间持续返回当前键号, 松开返回 0
 ***       主循环据此发速度命令(有键)或停止命令(无键)
 ***       消抖: 连续两次扫描一致才更新稳定值
 **********************************************************/

/* 扫描键盘, 返回当前按住的键号 (1-8), 0=无键按下 (速度模式: 按住持续返回) */
uint8_t Key_Scan(void);

#endif /* __KEYPAD_H */
